import { toJsLiteral } from '../pwa/source-literals'

export const FORUM_MARKDOWN_MODULE_PATH = ['utils']
export const FORUM_MARKDOWN_MODULE_NAME = 'forum-markdown'

/**
 * `utils/forum-markdown.js`: the allow-list renderer every piece of member
 * content goes through (plan 7.5). The whole text is HTML-escaped FIRST, then
 * the Markdown subset is recognised on the escaped text, so no character a
 * member typed ever reaches the page as markup: raw HTML renders as the text
 * it is. Links are http(s) only and open in a new tab with
 * `rel="nofollow ugc noopener"`; images only from `https://` or the project's
 * own upload base; `@handle` is emphasised text in v1 (no profile link: the
 * handle alone does not name the user id). Pure, CommonJS, no dependency —
 * the data module and the composer preview require the same file.
 */
export const buildForumMarkdownSource = (options: { storageBase?: string | null } = {}): string =>
  `'use strict';
// Forum Markdown renderer — generated by TeleportHQ. Pure: no I/O, no DOM.
// The project's upload base: baked when known, else the server's RUNTIME_STORAGE_URL
// (a browser preview has neither and keeps the https-only rule).
var STORAGE_BASE = ${toJsLiteral(options.storageBase || '')} ||
  (typeof process !== 'undefined' && process.env && process.env.RUNTIME_STORAGE_URL ? String(process.env.RUNTIME_STORAGE_URL) : '');
var ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
var MAX_LENGTH = 40000;

function escapeHtml(text) {
  return String(text == null ? '' : text).replace(/[&<>"']/g, function (ch) { return ESCAPES[ch]; });
}

// A URL a link may point at: http(s) only, nothing that could leave the
// attribute (the text is already escaped, so quotes are entities by now).
function linkUrl(raw) {
  var url = String(raw || '').trim();
  return /^https?:\\/\\/[^\\s]+$/i.test(url) ? url : null;
}

function imageUrl(raw) {
  var url = String(raw || '').trim();
  if (!/^[^\\s]+$/.test(url)) return null;
  if (/^https:\\/\\//i.test(url)) return url;
  return STORAGE_BASE && url.indexOf(STORAGE_BASE) === 0 ? url : null;
}

// Inline marks on ONE escaped line. Code spans are lifted out first so their
// content is never formatted, then put back as <code>.
function inline(text) {
  var spans = [];
  var out = text.replace(/\`([^\`\\n]+)\`/g, function (_m, code) {
    spans.push('<code>' + code + '</code>');
    return '\\u0000' + (spans.length - 1) + '\\u0000';
  });
  out = out.replace(/!\\[([^\\]]*)\\]\\(([^\\s()]+)\\)/g, function (_m, alt, url) {
    var src = imageUrl(url);
    return src ? '<img src="' + src + '" alt="' + alt + '" loading="lazy" />' : alt;
  });
  out = out.replace(/\\[([^\\]]+)\\]\\(([^\\s()]+)\\)/g, function (_m, label, url) {
    var href = linkUrl(url);
    return href
      ? '<a href="' + href + '" rel="nofollow ugc noopener" target="_blank">' + label + '</a>'
      : label;
  });
  // A bare address in the text is linked too; one already inside a tag is left.
  out = out.replace(/(^|[\\s(])(https?:\\/\\/[^\\s<)]+)/g, function (_m, lead, url) {
    return lead + '<a href="' + url + '" rel="nofollow ugc noopener" target="_blank">' + url + '</a>';
  });
  out = out.replace(/\\*\\*([^*\\n]+)\\*\\*/g, '<strong>$1</strong>');
  out = out.replace(/(^|[^\\w*])\\*([^*\\n]+)\\*(?!\\w)/g, '$1<em>$2</em>');
  out = out.replace(/(^|[^\\w_])_([^_\\n]+)_(?!\\w)/g, '$1<em>$2</em>');
  out = out.replace(/~~([^~\\n]+)~~/g, '<s>$1</s>');
  out = out.replace(/(^|[^\\w@])@([a-z0-9_]{3,40})\\b/gi, '$1<em class="forum-mention">@$2</em>');
  return out.replace(/\\u0000(\\d+)\\u0000/g, function (_m, index) { return spans[Number(index)]; });
}

function paragraph(lines) {
  return '<p>' + lines.map(inline).join('<br />') + '</p>';
}

var LIST_ITEM = /^(\\s*)([-*]|\\d+[.)])\\s+(.*)$/;

// A list of at most two levels: an item indented by two or more spaces under
// another item nests; deeper indents are flattened into that level.
function list(items) {
  var html = '';
  var open = null;
  var nested = [];
  var flushNested = function () {
    if (nested.length) html += list(nested);
    nested = [];
  };
  for (var i = 0; i < items.length; i++) {
    var item = items[i];
    if (item.depth > 0 && open) {
      nested.push({ depth: 0, ordered: item.ordered, text: item.text });
      continue;
    }
    if (open) { flushNested(); html += '</li>'; }
    if (!open || open !== (item.ordered ? 'ol' : 'ul')) {
      if (open) html += '</' + open + '>';
      open = item.ordered ? 'ol' : 'ul';
      html += '<' + open + '>';
    }
    html += '<li>' + inline(item.text);
  }
  if (open) { flushNested(); html += '</li></' + open + '>'; }
  return html;
}

function blocks(lines, depth) {
  var html = '';
  var i = 0;
  while (i < lines.length) {
    var line = lines[i];
    if (!line.trim()) { i++; continue; }
    var fence = /^\`\`\`\\s*([a-z0-9+-]*)\\s*$/i.exec(line);
    if (fence) {
      var code = [];
      i++;
      while (i < lines.length && !/^\`\`\`\\s*$/.test(lines[i])) code.push(lines[i++]);
      i++;
      html += '<pre><code' + (fence[1] ? ' class="language-' + fence[1] + '"' : '') + '>' + code.join('\\n') + '</code></pre>';
      continue;
    }
    var heading = /^(##|###)\\s+(.+?)\\s*#*\\s*$/.exec(line);
    if (heading) {
      var level = heading[1].length;
      html += '<h' + level + '>' + inline(heading[2]) + '</h' + level + '>';
      i++;
      continue;
    }
    if (/^\\s*([-*_])(\\s*\\1){2,}\\s*$/.test(line)) { html += '<hr />'; i++; continue; }
    // "> " reads as "&gt; " once escaped.
    if (/^&gt;/.test(line) && depth < 2) {
      var quoted = [];
      while (i < lines.length && /^&gt;/.test(lines[i])) quoted.push(lines[i++].replace(/^&gt; ?/, ''));
      html += '<blockquote>' + blocks(quoted, depth + 1) + '</blockquote>';
      continue;
    }
    if (LIST_ITEM.test(line)) {
      var items = [];
      var match;
      while (i < lines.length && (match = LIST_ITEM.exec(lines[i]))) {
        items.push({ depth: match[1].length >= 2 ? 1 : 0, ordered: /\\d/.test(match[2]), text: match[3] });
        i++;
      }
      html += list(items);
      continue;
    }
    var para = [];
    while (i < lines.length && lines[i].trim() && !/^(\`\`\`|##|&gt;)/.test(lines[i]) && !LIST_ITEM.test(lines[i])) {
      para.push(lines[i++]);
    }
    html += paragraph(para);
  }
  return html;
}

// Markdown (member text) -> HTML made only of the tags above.
function renderForumMarkdown(markdown) {
  var text = String(markdown == null ? '' : markdown).slice(0, MAX_LENGTH).replace(/\\r\\n?/g, '\\n');
  return blocks(escapeHtml(text).split('\\n'), 0);
}

// The words of a Markdown text, on one line, for search and excerpts.
function forumPlainText(markdown) {
  var text = String(markdown == null ? '' : markdown).slice(0, MAX_LENGTH).replace(/\\r\\n?/g, '\\n');
  text = text.replace(/\`\`\`[a-z0-9+-]*\\n?([\\s\\S]*?)\`\`\`/gi, ' $1 ');
  text = text.replace(/!\\[([^\\]]*)\\]\\([^)]*\\)/g, '$1');
  text = text.replace(/\\[([^\\]]+)\\]\\([^)]*\\)/g, '$1');
  text = text.replace(/^\\s*(#{1,6}|&gt;|>|[-*+]|\\d+[.)])\\s+/gm, '');
  text = text.replace(/^\\s*([-*_])(\\s*\\1){2,}\\s*$/gm, ' ');
  text = text.replace(/(\\*\\*|__|~~|\\*|_|\`)/g, '');
  return text.replace(/<[^>]*>/g, ' ').replace(/\\s+/g, ' ').trim();
}

module.exports = { renderForumMarkdown: renderForumMarkdown, forumPlainText: forumPlainText, escapeHtml: escapeHtml };
`
