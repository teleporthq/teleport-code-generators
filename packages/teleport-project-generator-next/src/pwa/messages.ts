/** Aliases for locale codes that name a listed language under another code. */
const LOCALE_ALIASES: Record<string, string> = {
  no: 'nb',
  nn: 'nb',
  iw: 'he',
  in: 'id',
  'zh-hant': 'zh-tw',
  'zh-hk': 'zh-tw',
  'zh-mo': 'zh-tw',
  'zh-hans': 'zh',
  'zh-cn': 'zh',
  'zh-sg': 'zh',
}

const normalizeLocale = (locale: string): string => locale.trim().toLowerCase().replace(/_/g, '-')

/**
 * The copy for `locale`: the exact code first (`pt-pt`, `zh-tw`), then its
 * language (`es-mx` → `es`), then English.
 */
export const resolvePwaMessages = (locale: string | undefined): PwaMessages => {
  if (!locale) {
    return PWA_MESSAGES[DEFAULT_PWA_LOCALE]
  }

  const normalized = normalizeLocale(locale)
  const exact = LOCALE_ALIASES[normalized] ?? normalized
  if (PWA_MESSAGES[exact]) {
    return PWA_MESSAGES[exact]
  }

  const language = normalized.split('-')[0]
  const byLanguage = LOCALE_ALIASES[language] ?? language
  return PWA_MESSAGES[byLanguage] ?? PWA_MESSAGES[DEFAULT_PWA_LOCALE]
}

/** The copy for every locale the project serves, keyed by the project's own locale codes. */
export const resolvePwaMessagesForLocales = (locales: string[]): Record<string, PwaMessages> =>
  locales.reduce<Record<string, PwaMessages>>((acc, locale) => {
    acc[locale] = resolvePwaMessages(locale)
    return acc
  }, {})
